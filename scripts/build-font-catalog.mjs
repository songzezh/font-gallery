import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const categories = [...html.matchAll(/data-font-category="([^"]+)"/g)].map(match => match[1]);
const catalog = {};

for (const category of categories) {
  const directory = path.join(root, 'fonts', category);
  const entries = await readdir(directory, { withFileTypes: true }).catch(error => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  catalog[category] = [];
  for (const entry of entries.filter(entry => entry.isDirectory())) {
    const relativePath = `fonts/${category}/${entry.name}`;
    const metadataPath = path.join(directory, entry.name, 'METADATA.pb');
    const metadata = await readFile(metadataPath, 'utf8').catch(error => {
      if (error.code === 'ENOENT') {
        console.warn(`Skipped ${relativePath}: missing METADATA.pb`);
        return null;
      }
      throw error;
    });
    if (metadata === null) continue;
    // Read the family name before the first protobuf message, never a variant name.
    const header = metadata.replace(/#.*$/gm, '').split('{', 1)[0];
    const match = header.match(/^\s*name\s*:\s*("(?:\\.|[^"\\])*")/m);
    if (!match) throw new Error(`${relativePath}/METADATA.pb: missing family name`);
    const name = JSON.parse(match[1]);
    if (!name.trim()) throw new Error(`${relativePath}/METADATA.pb: empty family name`);
    catalog[category].push({ name, path: relativePath });
  }
  catalog[category].sort((a, b) => a.name.localeCompare(b.name, 'en') || a.path.localeCompare(b.path, 'en'));
}

const output = '// Generated by scripts/build-font-catalog.mjs. Do not edit manually.\n'
  + `window.fontCatalog = ${JSON.stringify(catalog, null, 2)};\n`;
await writeFile(path.join(root, 'fonts', 'catalog.js'), output);
console.log(`Indexed ${Object.values(catalog).flat().length} font families.`);
